-- Description :
-- This VHDL module integrates an Nios V soft processor with an SPI interface
-- to communicate with the Analog Devices ADT7301 temperature sensor.
--
-- The system reads temperature data from the ADT7301 via the SPI bus and 
-- makes it available for further processing or display. The design is 
-- targeted for the Cyclone V SoC FPGA platform and serves as an example of 
-- sensor interfacing using soft-core processors and custom FPGA logic.
--
-- Key Features:
--   - SPI communication with ADT7301 temperature sensor
--   - Nios V soft processor integration
--   - Compatible with Intel Quartus Prime design flow
--   - Suitable for embedded control and monitoring applications
