-- Standard IEEE libraries for VHDL
library ieee;
use ieee.std_logic_1164.all;   	-- For std_logic and std_logic_vector types
use ieee.numeric_std.all;       -- For numeric operations on std_logic_vector

-------------------------------------------------------------------------------
-- Top-level entity declaration
-------------------------------------------------------------------------------
entity fpga_niosv is
port (
	-- SYSTEM CLOCK AND RESET
    iClock      	: in 	std_logic;  					-- 50 MHz system clock input
    inReset     	: in 	std_logic;  					-- Active-high system reset

	-- DDR3 MEMORY INTERFACE (NIOS V)
    DDR3_A        	: out   std_logic_vector(14 downto 0);  -- DDR3 address lines
    DDR3_BA       	: out   std_logic_vector(2 downto 0);   -- DDR3 bank address
    DDR3_CAS_n    	: out   std_logic_vector(0 downto 0);   -- Column address strobe (active low)
    DDR3_CKE      	: out   std_logic_vector(0 downto 0);   -- Clock enable
    DDR3_CK_n     	: out   std_logic_vector(0 downto 0);   -- Differential clock negative
    DDR3_CK_p     	: out   std_logic_vector(0 downto 0);   -- Differential clock positive
    DDR3_CS_n     	: out   std_logic_vector(0 downto 0);   -- Chip select (active low)
    DDR3_DM       	: out   std_logic_vector(3 downto 0);   -- Data mask for write operations
    DDR3_DQ       	: inout std_logic_vector(31 downto 0);  -- Data bus
    DDR3_DQS_n    	: inout std_logic_vector(3 downto 0);   -- Differential data strobe negative
    DDR3_DQS_p    	: inout std_logic_vector(3 downto 0);   -- Differential data strobe positive
    DDR3_ODT      	: out   std_logic_vector(0 downto 0);   -- On-die termination control
    DDR3_RAS_n    	: out   std_logic_vector(0 downto 0);   -- Row address strobe (active low)
    DDR3_RESET_n  	: out   std_logic;                      -- DDR3 reset (active low)
    DDR3_RZQ      	: in    std_logic;                      -- On-chip calibration resistor input
    DDR3_WE_n     	: out   std_logic_vector(0 downto 0);   -- Write enable (active low)

	-- TEMPERATURE SENSOR (ADT7301)
	TEMP_DIN		: in std_logic;   						-- SPI data input from sensor (MISO)
	TEMP_DOUT		: out std_logic;  						-- SPI data output to sensor (MOSI, optional for read-only operation)
	TEMP_SCLK		: out std_logic;  						-- SPI clock output
	TEMP_CS_n		: out std_logic   						-- SPI chip select (active low)
);
end entity;

